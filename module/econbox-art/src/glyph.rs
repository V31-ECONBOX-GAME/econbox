#[cfg(test)]
mod tests {
    use super::*;
    use crate::PIXELS;

    #[test]
    fn every_glyph_is_a_square_of_the_sprite_size() {
        for kind in GLYPHS {
            let rows = kind.template();

            for (y, row) in rows.iter().enumerate() {
                assert_eq!(row.chars().count(), SPRITE, "{kind:?} row {y}");
            }
        }
    }

    #[test]
    fn every_glyph_paints_something_and_only_known_glyphs() {
        for kind in GLYPHS {
            let rows = kind.template();
            let used: Vec<char> = rows.iter().flat_map(|row| row.chars()).collect();

            assert!(
                used.iter().all(|glyph| ".CDLABWE".contains(*glyph)),
                "{kind:?}"
            );
            assert!(
                glyph(kind, None).iter().filter(|px| px[3] > 0).count() > 12,
                "{kind:?}"
            );
            assert_eq!(glyph(kind, None).len(), PIXELS);
        }
    }

    #[test]
    fn no_two_glyphs_share_a_template() {
        for (at, kind) in GLYPHS.iter().enumerate() {
            for other in &GLYPHS[at + 1..] {
                assert_ne!(kind.template(), other.template(), "{kind:?} {other:?}");
            }
        }
    }
}
